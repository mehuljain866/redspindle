import json
import queue
import tempfile
import unittest
from pathlib import Path
from cd_prep import (
    calculate_disc_distribution,
    cleanup_stale_disc_folders,
    estimate_track_size_bytes,
    export_cd_discs,
)


class CDCurationTests(unittest.TestCase):
    def test_estimate_track_size(self):
        # 180s track at 192k: (192 * 1000 / 8) * 180 + 85000 = 4,405,000 bytes
        est = estimate_track_size_bytes(180.0, 0, "192k")
        self.assertGreater(est, 4_000_000)
        self.assertLess(est, 5_000_000)

    def test_data_cd_packing_by_byte_size(self):
        """Data CD packs until 700 MB limit (minus safe margin) is approached."""
        # 150 tracks of ~4.5 MB each (~675 MB)
        tracks = [
            {"path": f"track_{i}.mp3", "duration": 180.0, "size": 4_500_000, "title": f"Song {i}"}
            for i in range(150)
        ]
        discs = calculate_disc_distribution(
            tracks,
            disc_capacity_mb=700.0,
            target_bitrate="192k",
            safe_margin_mb=10.0,
            is_audio_cd=False,
        )
        self.assertEqual(len(discs), 1)
        self.assertEqual(discs[0]["disc_number"], 1)
        self.assertFalse(discs[0]["is_audio_cd"])
        self.assertLessEqual(discs[0]["total_mb"], 700.0)

    def test_audio_cd_packing_by_duration(self):
        """Audio CD (CD-DA) packs tracks by time duration (78 min safe threshold)."""
        # 30 tracks of 4 minutes (240s) each = 120 minutes total -> requires 2 discs
        tracks = [
            {"path": f"track_{i}.mp3", "duration": 240.0, "size": 6_000_000, "title": f"Song {i}"}
            for i in range(30)
        ]
        discs = calculate_disc_distribution(
            tracks,
            is_audio_cd=True,
            max_audio_cd_minutes=80.0,
        )
        # Safe limit is 78 mins = 19.5 tracks -> 19 tracks on Disc 1 (76 mins), 11 on Disc 2 (44 mins)
        self.assertEqual(len(discs), 2)
        self.assertTrue(discs[0]["is_audio_cd"])
        self.assertLessEqual(discs[0]["total_duration_min"], 78.0)
        self.assertEqual(len(discs[0]["tracks"]), 19)
        self.assertEqual(len(discs[1]["tracks"]), 11)

    def test_audio_cd_74_minute_variant(self):
        """74-minute disc safe limit is 72 minutes."""
        # 20 tracks of 4.5 minutes (270s) each = 90 minutes total
        tracks = [
            {"path": f"track_{i}.mp3", "duration": 270.0, "size": 6_000_000, "title": f"Song {i}"}
            for i in range(20)
        ]
        discs = calculate_disc_distribution(
            tracks,
            is_audio_cd=True,
            max_audio_cd_minutes=74.0,
        )
        # Safe limit is 72 mins = 16 tracks (72 mins) -> Disc 1 has 16, Disc 2 has 4
        self.assertEqual(len(discs), 2)
        self.assertLessEqual(discs[0]["total_duration_min"], 72.0)
        self.assertEqual(len(discs[0]["tracks"]), 16)
        self.assertEqual(len(discs[1]["tracks"]), 4)

    def test_stale_disc_cleanup_uses_production_helper_and_preserves_user_files(self):
        with tempfile.TemporaryDirectory() as tmpdir:
            output = Path(tmpdir)
            stale = output / "Disc 3"
            stale.mkdir()
            old_track = stale / "09 - OldSong.mp3"
            old_track.write_text("generated track")
            old_playlist = stale / "playlist.m3u"
            old_playlist.write_text("generated playlist")
            user_file = stale / "notes.md"
            user_file.write_text("keep me")
            user_audio = stale / "manual-track.mp3"
            user_audio.write_text("not generated by Red Spindle")

            removed = cleanup_stale_disc_folders(output, {1, 2})
            self.assertEqual(removed, [])  # User files prevent removing the folder.
            self.assertFalse(old_track.exists())
            self.assertFalse(old_playlist.exists())
            self.assertTrue(user_file.exists())
            self.assertTrue(user_audio.exists())

    def test_stale_empty_disc_folder_is_removed(self):
        with tempfile.TemporaryDirectory() as tmpdir:
            output = Path(tmpdir)
            stale = output / "Disc 4"
            stale.mkdir()
            (stale / "01 - OldSong.flac").write_text("generated track")
            removed = cleanup_stale_disc_folders(output, {1})
            self.assertEqual(removed, ["Disc 4"])
            self.assertFalse(stale.exists())

    def test_audio_cd_export_emits_done_and_writes_manifest(self):
        """Audio CD exports must not skip playlist generation or the DONE queue event."""
        with tempfile.TemporaryDirectory() as src_dir, tempfile.TemporaryDirectory() as out_dir:
            src_path = Path(src_dir)
            out_path = Path(out_dir)

            t1 = src_path / "song1.mp3"
            t1.write_bytes(b"dummy audio content 1")
            t2 = src_path / "song2.mp3"
            t2.write_bytes(b"dummy audio content 2")

            tracks = [
                {"path": str(t1), "title": "First Song", "artist": "Artist A", "duration": 180.0, "size": len(t1.read_bytes())},
                {"path": str(t2), "title": "Second Song", "artist": "Artist B", "duration": 200.0, "size": len(t2.read_bytes())},
            ]
            discs = calculate_disc_distribution(tracks, is_audio_cd=True, max_audio_cd_minutes=80.0)

            q = queue.Queue()
            summary = export_cd_discs(
                discs=discs,
                out_dir=out_path,
                bitrate="original",
                is_audio_cd=True,
                max_mins=80.0,
                progress_queue=q,
            )

            # Check that DONE event was queued
            events = []
            while not q.empty():
                events.append(q.get_nowait())

            terminal_events = [e for e in events if e[0] in ("DONE", "ERROR", "CANCELLED")]
            self.assertEqual(len(terminal_events), 1)
            self.assertEqual(terminal_events[0][0], "DONE")
            self.assertEqual(summary["succeeded"], 2)
            self.assertEqual(summary["failed"], 0)

            # Verify files on disk
            disc1 = out_path / "Disc 1"
            self.assertTrue(disc1.exists())
            self.assertTrue((disc1 / "playlist.m3u").exists())
            self.assertTrue((disc1 / "disc_tracklist.txt").exists())
            manifest_file = out_path / "cd_burn_manifest.json"
            self.assertTrue(manifest_file.exists())

            manifest = json.loads(manifest_file.read_text(encoding="utf-8"))
            self.assertEqual(manifest["disc_type"], "audio_cd")
            self.assertEqual(manifest["total_exported"], 2)

    def test_data_cd_export_emits_done_and_writes_manifest(self):
        """Data CD exports emit DONE and generate playlists within safe byte capacities."""
        with tempfile.TemporaryDirectory() as src_dir, tempfile.TemporaryDirectory() as out_dir:
            src_path = Path(src_dir)
            out_path = Path(out_dir)

            t1 = src_path / "song1.mp3"
            t1.write_bytes(b"dummy audio content 1")
            tracks = [
                {"path": str(t1), "title": "First Song", "artist": "Artist A", "duration": 180.0, "size": len(t1.read_bytes())},
            ]
            discs = calculate_disc_distribution(tracks, disc_capacity_mb=700.0, is_audio_cd=False)

            q = queue.Queue()
            summary = export_cd_discs(
                discs=discs,
                out_dir=out_path,
                bitrate="original",
                is_audio_cd=False,
                progress_queue=q,
            )

            events = []
            while not q.empty():
                events.append(q.get_nowait())

            terminal_events = [e for e in events if e[0] in ("DONE", "ERROR", "CANCELLED")]
            self.assertEqual(len(terminal_events), 1)
            self.assertEqual(terminal_events[0][0], "DONE")
            self.assertEqual(summary["succeeded"], 1)

            manifest_file = out_path / "cd_burn_manifest.json"
            self.assertTrue(manifest_file.exists())
            manifest = json.loads(manifest_file.read_text(encoding="utf-8"))
            self.assertEqual(manifest["disc_type"], "data_cd")
            self.assertEqual(manifest["total_exported"], 1)

    def test_data_cd_post_transcode_capacity_guard_raises_and_cleans_files(self):
        """Over-capacity Data CD exports raise RuntimeError and remove newly exported files."""
        with tempfile.TemporaryDirectory() as src_dir, tempfile.TemporaryDirectory() as out_dir:
            src_path = Path(src_dir)
            out_path = Path(out_dir)

            t1 = src_path / "large.mp3"
            # 2 MB dummy file
            t1.write_bytes(b"x" * (2 * 1024 * 1024))
            tracks = [
                {"path": str(t1), "title": "Large Track", "artist": "Artist L", "duration": 60.0, "size": len(t1.read_bytes())},
            ]
            # Safe bytes minimum limit is max(50.0, capacity - 10) MB = 50 MB,
            # so let's pre-populate the disc folder with existing files that exceed 50 MB:
            disc1 = out_path / "Disc 1"
            disc1.mkdir(parents=True)
            big_user_file = disc1 / "existing_user_archive.zip"
            big_user_file.write_bytes(b"0" * (51 * 1024 * 1024))

            discs = [{
                "disc_number": 1,
                "tracks": tracks,
                "capacity_mb": 60.0,
                "is_audio_cd": False,
            }]

            with self.assertRaises(RuntimeError) as cm:
                export_cd_discs(
                    discs=discs,
                    out_dir=out_path,
                    bitrate="original",
                    is_audio_cd=False,
                )
            self.assertIn("Post-transcode capacity check failed", str(cm.exception))
            # The generated track should have been cleaned up
            generated_track = disc1 / "01 - large.mp3"
            self.assertFalse(generated_track.exists())
            # The pre-existing user file remains safe
            self.assertTrue(big_user_file.exists())


if __name__ == "__main__":
    unittest.main()
